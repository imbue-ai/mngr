class AdoptionEndpointKind(UpperCaseStrEnum):
    """Which of the slice's two sshd endpoints a rotation targets."""

    VM = auto()
    CONTAINER = auto()


class PendingHostKeyRotation(FrozenModel):
    """Client-persisted state of an in-flight host-key rotation for one endpoint.

    Written before the host is touched, so a crash at any later step leaves
    enough on disk to converge: the new keypair (to re-install or pin) and the
    old public key (to recognize an endpoint the install never reached).
    """

    kind: AdoptionEndpointKind = Field(description="Which endpoint is being rotated")
    old_public_key: str | None = Field(description="The public key pinned before the rotation began, if any")
    new_private_key_pem: str = Field(description="The freshly-generated host private key (OpenSSH PEM)")
    new_public_key: str = Field(description="The freshly-generated host public key (one OpenSSH line)")
    started_at: datetime = Field(description="When the rotation began")


class PendingClientKeyRotation(FrozenModel):
    """Client-persisted state of an in-flight per-host client-key rotation."""

    old_public_key: str = Field(description="The client public key being retired")
    new_public_key: str = Field(description="The freshly-generated client public key")
    started_at: datetime = Field(description="When the rotation began")


class AdoptionMarker(FrozenModel):
    """Client-side record that this host has been adopted (per-host state dir)."""

    adopted_at: datetime = Field(description="When adoption completed on this machine")
    verified_schema_version: int = Field(
        # Markers written before the field existed parse as 0: below every real
        # version, so such a host gets exactly one full re-verification (which
        # also runs the historical heals, e.g. RSA -> Ed25519) and is then
        # stamped current.
        default=0,
        description=(
            "The ADOPTION_SCHEMA_VERSION this host was last fully verified at. A successful "
            "verification is durable: no SSH-visiting re-verification happens again until this "
            "falls behind ADOPTION_SCHEMA_VERSION (a code migration), the stamp is invalidated "
            "(restart/relocation may replay cloud-init), or local pending-rotation/RSA-key "
            "evidence says key work is unfinished."
        ),
    )


