@pure
def is_slice_lease(container_ssh_port: int, configured_container_publish_port: int) -> bool:
    """Whether a lease points at a slice (lima VM on a box) rather than a plain OVH VPS.

    A slice's container is reached at a box-forwarded port that differs from the
    fixed in-VM publish port; an OVH VPS publishes and serves on the same port.
    Adoption covers slices only.
    """
    return container_ssh_port != configured_container_publish_port


@pure
def render_desired_authorized_keys(existing_content: str | None, required_keys: tuple[str, ...]) -> str:
    """Render the desired-state ``authorized_keys``: every existing line, plus the required keys.

    Existing lines are preserved verbatim (this keeps the pool management key
    and the bake key authorized -- pool-key stripping is a deliberately deferred
    later phase, at which point it becomes a content change here). Required
    keys already present are not duplicated.
    """
    lines: list[str] = []
    for raw_line in (existing_content or "").splitlines():
        line = raw_line.rstrip()
        if line and line not in lines:
            lines.append(line)
    for key in required_keys:
        stripped = key.strip()
        if stripped and stripped not in lines:
            lines.append(stripped)
    return "".join(f"{line}\n" for line in lines)


@pure
def remove_key_from_desired_authorized_keys(desired_content: str, retired_key: str) -> str:
    """Drop one key line from a rendered desired-state file (used when retiring a rotated client key)."""
    retired = retired_key.strip()
    kept = [line for line in desired_content.splitlines() if line.strip() != retired]
    return "".join(f"{line}\n" for line in kept)


@pure
def render_reconciler_script() -> str:
    """The in-VM script that re-asserts the desired authorized_keys and sshd host key."""
    return f"""\
#!/bin/sh
# Managed by mngr (slice adoption): re-assert the mngr-owned SSH material.
# cloud-init replays the carve's provision scripts on every VM start (each
# start regenerates cidata with a fresh instance-id), which resets root's
# authorized_keys and the sshd host key to their bake-time values; this puts
# the user's desired state back. Runs at every boot (ordered after cloud-init)
# and whenever the desired state changes.
set -eu
install -d -m 700 -o root -g root /root/.ssh
if [ -f {_DESIRED_AUTHORIZED_KEYS_PATH} ]; then
    install -m 600 -o root -g root {_DESIRED_AUTHORIZED_KEYS_PATH} /root/.ssh/authorized_keys
fi
if [ -f {_DESIRED_HOST_KEY_PATH} ] && [ -f {_DESIRED_HOST_KEY_PATH}.pub ]; then
    if ! cmp -s {_DESIRED_HOST_KEY_PATH} /etc/ssh/ssh_host_ed25519_key; then
        install -m 600 -o root -g root {_DESIRED_HOST_KEY_PATH} /etc/ssh/ssh_host_ed25519_key
        install -m 644 -o root -g root {_DESIRED_HOST_KEY_PATH}.pub /etc/ssh/ssh_host_ed25519_key.pub
        rm -f /etc/ssh/ssh_host_rsa_key /etc/ssh/ssh_host_rsa_key.pub
        rm -f /etc/ssh/ssh_host_ecdsa_key /etc/ssh/ssh_host_ecdsa_key.pub
        rm -f /etc/ssh/ssh_host_dsa_key /etc/ssh/ssh_host_dsa_key.pub
        systemctl reload ssh 2>/dev/null || systemctl reload sshd 2>/dev/null || pkill -HUP -x sshd || true
    fi
fi
"""


@pure
def render_reconciler_unit() -> str:
    """The systemd unit that runs the reconciler script on every boot, after cloud-init's replay."""
    return f"""\
[Unit]
Description=Re-assert mngr-owned SSH material (root authorized_keys + sshd host key)
# cloud-init replays the carve's provision scripts on every boot (fresh
# instance-id), resetting the SSH material to bake-time values; running after
# it makes the user's desired state win.
After=cloud-final.service cloud-init.target ssh.service

[Service]
Type=oneshot
ExecStart={_RECONCILER_SCRIPT_PATH}

[Install]
# Activated by cloud-init.target, NOT multi-user.target: cloud-final.service is
# itself ordered After=multi-user.target, so a unit wanted by multi-user.target
# that is also After=cloud-final.service creates an ordering cycle, and systemd
# resolves it by deleting THIS unit's start job -- the reconciler then never
# runs on any boot. This unit is explicitly After=cloud-init.target (which is
# itself after cloud-final.service), so hanging off cloud-init.target gives
# cloud-final -> cloud-init.target -> reconciler with no cycle.
WantedBy=cloud-init.target
"""


@pure
def _build_write_file_command(path: str, content: str, mode: str) -> str:
    """One shell statement that writes ``content`` to ``path`` (via base64, dodging all quoting) and chmods it."""
    encoded = base64.b64encode(content.encode()).decode()
    return f"mkdir -p $(dirname {path}) && printf '%s' {encoded} | base64 -d > {path} && chmod {mode} {path}"


@pure
def expected_reconciler_content_hash() -> str:
    """The sha256 of the unit + script this client version installs, matching the in-VM read.

    Compared against the hash :func:`build_read_reconciler_state_command` reports
    (``cat unit script | sha256sum``, same concatenation order) so the heal pass
    reinstalls when a VM carries an older client version's reconciler content --
    an ``enabled`` unit alone says nothing about whether its content is current.
    """
    return hashlib.sha256((render_reconciler_unit() + render_reconciler_script()).encode()).hexdigest()


@pure
def build_reconciler_install_command(desired_authorized_keys: str) -> str:
    """Shell command that installs/refreshes the reconciler and runs it once (asserting the state now)."""
    steps = [
        "set -eu",
        _build_write_file_command(_DESIRED_AUTHORIZED_KEYS_PATH, desired_authorized_keys, "600"),
        _build_write_file_command(_RECONCILER_SCRIPT_PATH, render_reconciler_script(), "755"),
        _build_write_file_command(_RECONCILER_UNIT_PATH, render_reconciler_unit(), "644"),
        "systemctl daemon-reload",
        # reenable (not enable): enable only adds symlinks for the CURRENT
        # [Install] section, so a unit previously enabled under a different
        # WantedBy target keeps its stale symlink -- and the stale
        # multi-user.target edge is exactly what created the ordering cycle
        # this unit's [Install] comment describes. reenable drops every
        # existing enablement symlink first.
        f"systemctl reenable {RECONCILER_UNIT_NAME}",
        _RECONCILER_SCRIPT_PATH,
    ]
    return "\n".join(steps)


@pure
def build_read_reconciler_state_command() -> str:
    """Shell command that prints the reconciler's enablement + desired/live state as marker lines."""
    return f"""\
enabled=$(systemctl is-enabled {RECONCILER_UNIT_NAME} 2>/dev/null || echo unknown)
echo "{_RECONCILER_ENABLED_PREFIX}$enabled"
if [ -f {_DESIRED_AUTHORIZED_KEYS_PATH} ]; then
    echo "{_DESIRED_B64_PREFIX}$(base64 -w0 {_DESIRED_AUTHORIZED_KEYS_PATH})"
else
    echo "{_DESIRED_B64_PREFIX}{_DESIRED_ABSENT_VALUE}"
fi
if cmp -s {_DESIRED_AUTHORIZED_KEYS_PATH} /root/.ssh/authorized_keys 2>/dev/null; then
    echo "{_LIVE_MATCHES_PREFIX}1"
else
    echo "{_LIVE_MATCHES_PREFIX}0"
fi
if [ -f {_RECONCILER_UNIT_PATH} ] && [ -f {_RECONCILER_SCRIPT_PATH} ]; then
    echo "{_INSTALLED_HASH_PREFIX}$(cat {_RECONCILER_UNIT_PATH} {_RECONCILER_SCRIPT_PATH} | sha256sum | cut -d' ' -f1)"
else
    echo "{_INSTALLED_HASH_PREFIX}{_DESIRED_ABSENT_VALUE}"
fi
"""


@pure
def parse_reconciler_state_output(stdout: str) -> SliceReconcilerState:
    """Parse the marker lines printed by :func:`build_read_reconciler_state_command`."""
    is_unit_enabled = False
    desired: str | None = None
    is_live_matching = False
    installed_content_hash: str | None = None
    for line in stdout.splitlines():
        stripped = line.strip()
        if stripped.startswith(_RECONCILER_ENABLED_PREFIX):
            is_unit_enabled = stripped.removeprefix(_RECONCILER_ENABLED_PREFIX) == "enabled"
        elif stripped.startswith(_DESIRED_B64_PREFIX):
            value = stripped.removeprefix(_DESIRED_B64_PREFIX)
            desired = None if value == _DESIRED_ABSENT_VALUE else base64.b64decode(value).decode()
        elif stripped.startswith(_LIVE_MATCHES_PREFIX):
            is_live_matching = stripped.removeprefix(_LIVE_MATCHES_PREFIX) == "1"
        elif stripped.startswith(_INSTALLED_HASH_PREFIX):
            hash_value = stripped.removeprefix(_INSTALLED_HASH_PREFIX)
            installed_content_hash = None if hash_value == _DESIRED_ABSENT_VALUE else hash_value
        else:
            continue
    return SliceReconcilerState(
        is_unit_enabled=is_unit_enabled,
        desired_authorized_keys=desired,
        is_live_matching_desired=is_live_matching,
        installed_content_hash=installed_content_hash,
    )


@pure
def build_vm_host_key_install_command(private_key_pem: str, public_key: str) -> str:
    """Shell command that installs a new VM sshd host key (desired copy + live) and reloads sshd.

    The desired copy under /etc/mngr is what the reconciler re-asserts after
    every boot, defeating cloud-init's replay of the bake-time key.
    """
    steps = [
        "set -eu",
        _build_write_file_command(_DESIRED_HOST_KEY_PATH, private_key_pem, "600"),
        _build_write_file_command(f"{_DESIRED_HOST_KEY_PATH}.pub", public_key.strip() + "\n", "644"),
        f"install -m 600 -o root -g root {_DESIRED_HOST_KEY_PATH} /etc/ssh/ssh_host_ed25519_key",
        f"install -m 644 -o root -g root {_DESIRED_HOST_KEY_PATH}.pub /etc/ssh/ssh_host_ed25519_key.pub",
        "rm -f /etc/ssh/ssh_host_rsa_key /etc/ssh/ssh_host_rsa_key.pub",
        "rm -f /etc/ssh/ssh_host_ecdsa_key /etc/ssh/ssh_host_ecdsa_key.pub",
        "rm -f /etc/ssh/ssh_host_dsa_key /etc/ssh/ssh_host_dsa_key.pub",
        "systemctl reload ssh 2>/dev/null || systemctl reload sshd 2>/dev/null || pkill -HUP -x sshd",
    ]
    return "\n".join(steps)


@pure
def _resolve_container_id_snippet(host_id: HostId) -> str:
    """Shell lines that resolve the workspace's running container id into ``$cid`` (or exit 41)."""
    return (
        f"cid=$(docker ps -q --filter label=com.imbue.mngr.host-id={host_id} | head -1)\n"
        '[ -n "$cid" ] || { echo "no running workspace container" >&2; exit 41; }'
    )


@pure
def build_container_host_key_install_command(host_id: HostId, private_key_pem: str, public_key: str) -> str:
    """Shell command (run in the VM) that installs a new container sshd host key and reloads its sshd.

    The container's sshd is HUPed so its master re-execs and picks up the new
    key without dropping established sessions; if no master is running, one is
    started fresh (the container's CMD never starts sshd itself).
    """
    encoded_private = base64.b64encode(private_key_pem.encode()).decode()
    encoded_public = base64.b64encode((public_key.strip() + "\n").encode()).decode()
    start_sshd = build_start_sshd_command()
    steps = [
        "set -eu",
        _resolve_container_id_snippet(host_id),
        f"printf '%s' {encoded_private} | base64 -d | docker exec -i \"$cid\" sh -c "
        "'umask 077; cat > /etc/ssh/ssh_host_ed25519_key'",
        f"printf '%s' {encoded_public} | base64 -d | docker exec -i \"$cid\" sh -c "
        "'umask 022; cat > /etc/ssh/ssh_host_ed25519_key.pub'",
        # The HUP must match by comm (-x), not by cmdline: OpenSSH >= 9.8
        # retitles the listening master to "sshd: /usr/sbin/sshd ...", so a
        # cmdline anchor like ^/usr/sbin/sshd matches nothing and the reload
        # silently never happens (the endpoint keeps serving the old key until
        # the rotation's served-key poll times out). comm stays "sshd" for the
        # master while per-connection "sshd-session" children are not matched,
        # so established sessions survive the re-exec.
        'docker exec "$cid" sh -c '
        "'chmod 600 /etc/ssh/ssh_host_ed25519_key; chmod 644 /etc/ssh/ssh_host_ed25519_key.pub; "
        "rm -f /etc/ssh/ssh_host_rsa_key /etc/ssh/ssh_host_rsa_key.pub "
        "/etc/ssh/ssh_host_ecdsa_key /etc/ssh/ssh_host_ecdsa_key.pub "
        "/etc/ssh/ssh_host_dsa_key /etc/ssh/ssh_host_dsa_key.pub; "
        "pkill -HUP -x sshd || true'",
        # If no sshd master was there to HUP, start one fresh (guarded no-op otherwise).
        f'docker exec -d "$cid" sh -c {shlex.quote(f"{start_sshd} &")}',
    ]
    return "\n".join(steps)


@pure
def build_container_authorized_key_append_command(host_id: HostId, public_key: str) -> str:
    """Shell command (run in the VM) that idempotently appends a client key to the container root's authorized_keys."""
    quoted_key = shlex.quote(public_key.strip())
    inner = (
        'mkdir -p /root/.ssh && chmod 700 /root/.ssh && AK=/root/.ssh/authorized_keys && touch "$AK" && '
        'if [ -n "$(tail -c1 "$AK")" ]; then printf \'\\n\' >> "$AK"; fi && '
        f'(grep -qxF {quoted_key} "$AK" || printf \'%s\\n\' {quoted_key} >> "$AK") && '
        'chmod 600 "$AK"'
    )
    return f'set -eu\n{_resolve_container_id_snippet(host_id)}\ndocker exec "$cid" sh -c {shlex.quote(inner)}'


@pure
def build_container_authorized_key_remove_command(host_id: HostId, public_key: str) -> str:
    """Shell command (run in the VM) that removes one client key line from the container root's authorized_keys."""
    quoted_key = shlex.quote(public_key.strip())
    inner = (
        'AK=/root/.ssh/authorized_keys && [ -f "$AK" ] || exit 0 && '
        f'(grep -vxF {quoted_key} "$AK" > "$AK.mngr-tmp" || true) && '
        'cat "$AK.mngr-tmp" > "$AK" && rm -f "$AK.mngr-tmp" && chmod 600 "$AK"'
    )
    return f'set -eu\n{_resolve_container_id_snippet(host_id)}\ndocker exec "$cid" sh -c {shlex.quote(inner)}'


def _pending_host_key_rotation_path(host_state_dir: Path, kind: AdoptionEndpointKind) -> Path:
    return host_state_dir / _PENDING_HOST_KEY_ROTATION_FILENAME_TEMPLATE.format(kind=kind.lower())


def load_pending_host_key_rotation(host_state_dir: Path, kind: AdoptionEndpointKind) -> PendingHostKeyRotation | None:
    """Read the persisted in-flight rotation for one endpoint, or None when there is none."""
    path = _pending_host_key_rotation_path(host_state_dir, kind)
    if not path.exists():
        return None
    try:
        return PendingHostKeyRotation.model_validate_json(path.read_text())
    except (OSError, ValueError) as e:
        logger.warning("Could not parse pending host-key rotation state {} (ignoring it): {}", path, e)
        return None


def _save_pending_host_key_rotation(host_state_dir: Path, pending: PendingHostKeyRotation) -> None:
    path = _pending_host_key_rotation_path(host_state_dir, pending.kind)
    atomic_write(path, pending.model_dump_json(indent=2))
    path.chmod(0o600)


def _clear_pending_host_key_rotation(host_state_dir: Path, kind: AdoptionEndpointKind) -> None:
    _pending_host_key_rotation_path(host_state_dir, kind).unlink(missing_ok=True)


def adoption_marker_path(host_state_dir: Path) -> Path:
    """The client-side marker recording that this host has been adopted."""
    return host_state_dir / ADOPTION_MARKER_FILENAME


def load_adoption_marker(host_state_dir: Path) -> AdoptionMarker | None:
    """Read the adoption marker, or None when the host has not been adopted from this machine."""
    path = adoption_marker_path(host_state_dir)
    if not path.exists():
        return None
    try:
        return AdoptionMarker.model_validate_json(path.read_text())
    except (OSError, ValueError) as e:
        logger.warning("Could not parse adoption marker {} (treating the host as unadopted): {}", path, e)
        return None


def _write_adoption_marker(host_state_dir: Path) -> None:
    atomic_write(
        adoption_marker_path(host_state_dir),
        AdoptionMarker(
            adopted_at=datetime.now(timezone.utc),
            verified_schema_version=ADOPTION_SCHEMA_VERSION,
        ).model_dump_json(indent=2),
    )


def _stamp_marker_verified(host_state_dir: Path, marker: AdoptionMarker) -> None:
    """Record a successful full verification, preserving the original adoption time."""
    atomic_write(
        adoption_marker_path(host_state_dir),
        marker.model_copy_update(
            to_update(marker.field_ref().verified_schema_version, ADOPTION_SCHEMA_VERSION),
        ).model_dump_json(indent=2),
    )


def invalidate_adoption_verification(host_state_dir: Path) -> None:
    """Force the next host build to run a full SSH-visiting re-verification.

    Called by the restart/relocation paths, where the VM may have replayed
    cloud-init over the SSH material (or moved to a different box entirely).
    The host stays adopted -- only the durable verified stamp is reset.
    """
    marker = load_adoption_marker(host_state_dir)
    if marker is None:
        return
    atomic_write(
        adoption_marker_path(host_state_dir),
        marker.model_copy_update(
            to_update(marker.field_ref().verified_schema_version, 0),
        ).model_dump_json(indent=2),
    )


def _endpoint_pin(known_hosts_path: Path, host_id: HostId, address: str, port: int) -> HostKeyPin | None:
    """The host's stored pin for one endpoint (any keytype; there is at most one, ed25519)."""
    record = load_host_key_record(known_hosts_path, host_id)
    if record is None:
        return None
    for pin in record.pins:
        if pin.address == address and pin.port == port:
            return pin
    return None


@pure
def _endpoint_port(target: SliceAdoptionTarget, kind: AdoptionEndpointKind) -> int:
    """The box-forwarded port of one of the slice's two sshd endpoints."""
    match kind:
        case AdoptionEndpointKind.VM:
            return target.vm_port
        case AdoptionEndpointKind.CONTAINER:
            return target.container_port
        case _ as unreachable:
            assert_never(unreachable)


def rotate_endpoint_host_key(
    access: SliceVmAccessInterface,
    target: SliceAdoptionTarget,
    kind: AdoptionEndpointKind,
) -> str:
    """Rotate one endpoint's sshd host key to a fresh user-generated key; returns the new public key.

    Two-phase and crash-safe: the new keypair is persisted client-side before
    the host is touched, the install is decided by an unauthenticated probe of
    which key the endpoint actually serves (so a crash between install and pin
    is recovered by re-running), and the user-origin pin is written only after
    the endpoint demonstrably serves the new key.
    """
    port = _endpoint_port(target, kind)
    pending = load_pending_host_key_rotation(target.host_state_dir, kind)
    if pending is None:
        private_key_pem, public_key = generate_ed25519_host_keypair()
        existing_pin = _endpoint_pin(target.known_hosts_path, target.host_id, target.address, port)
        pending = PendingHostKeyRotation(
            kind=kind,
            old_public_key=existing_pin.public_key if existing_pin is not None else None,
            new_private_key_pem=private_key_pem,
            new_public_key=public_key,
            started_at=datetime.now(timezone.utc),
        )
        _save_pending_host_key_rotation(target.host_state_dir, pending)

    # Install unless the endpoint already serves the new key (a resumed run).
    if not access.is_endpoint_serving_host_key(port, pending.new_public_key):
        with log_span("Installing rotated {} host key for host {}", kind, target.host_id):
            match kind:
                case AdoptionEndpointKind.VM:
                    access.install_vm_host_key(pending.new_private_key_pem, pending.new_public_key)
                case AdoptionEndpointKind.CONTAINER:
                    access.install_container_host_key(pending.new_private_key_pem, pending.new_public_key)
                case _ as unreachable:
                    assert_never(unreachable)
        new_public_key = pending.new_public_key
        if not poll_until(
            lambda: access.is_endpoint_serving_host_key(port, new_public_key),
            timeout=_SERVED_KEY_POLL_TIMEOUT_SECONDS,
            poll_interval=_SERVED_KEY_POLL_INTERVAL_SECONDS,
        ):
            raise AdoptionError(
                f"endpoint {target.address}:{port} ({kind}) did not serve the rotated host key within "
                f"{_SERVED_KEY_POLL_TIMEOUT_SECONDS:.0f}s; the previous key and pin are unchanged"
            )

    # The endpoint provably serves the new key: pin it user-origin (replacing
    # the bootstrap pin; the store's precedence keeps any later bootstrap
    # write from displacing it), then retire the pending state.
    add_host_to_known_hosts(
        target.known_hosts_path,
        target.address,
        port,
        pending.new_public_key,
        host_id=target.host_id,
        origin=HostKeyOrigin.USER,
    )
    _clear_pending_host_key_rotation(target.host_state_dir, kind)
    return pending.new_public_key


def complete_pending_host_key_rotations(access: SliceVmAccessInterface, target: SliceAdoptionTarget) -> None:
    """Finish any rotation a previous run left in flight (no-op when none are pending)."""
    for kind in AdoptionEndpointKind:
        if load_pending_host_key_rotation(target.host_state_dir, kind) is not None:
            logger.debug("Resuming in-flight {} host-key rotation for host {}", kind, target.host_id)
            rotate_endpoint_host_key(access, target, kind)


def _adopt(access: SliceVmAccessInterface, target: SliceAdoptionTarget) -> None:
    """Run full adoption: reconciler install, both host-key rotations, then the marker.

    A host another of the user's devices already adopted (the installed
    reconciler is its fingerprint) is verified and healed instead of re-adopted:
    the client-side marker is per-device, but adoption itself must happen once
    per host -- re-rotating the host keys here would displace the sibling
    device's user-origin pins out from under it, and the synced record is the
    channel through which this device already received (or will receive) the
    adopted trust material.
    """
    reconciler_state = access.read_reconciler_state()
    if reconciler_state.is_unit_enabled and reconciler_state.desired_authorized_keys is not None:
        logger.debug(
            "Host {} was already adopted by another device (reconciler present); verifying instead of re-adopting",
            target.host_id,
        )
        _verify_and_heal(access, target)
        _write_adoption_marker(target.host_state_dir)
        return
    with log_span("Adopting leased slice {}", target.host_id):
        current_authorized_keys = access.read_vm_root_authorized_keys()
        desired = render_desired_authorized_keys(current_authorized_keys, (target.client_public_key,))
        access.install_reconciler(desired)
        rotate_endpoint_host_key(access, target, AdoptionEndpointKind.VM)
        rotate_endpoint_host_key(access, target, AdoptionEndpointKind.CONTAINER)
        _write_adoption_marker(target.host_state_dir)
    logger.info("Adopted leased slice {} (reconciler installed, both host keys rotated)", target.host_id)


def _verify_and_heal(access: SliceVmAccessInterface, target: SliceAdoptionTarget) -> None:
    """Re-verify an adopted host and heal drift (called at most once per process, and after start/rebuild)."""
    complete_pending_host_key_rotations(access, target)

    # The reconciler and its desired state: reinstall whenever the unit is off,
    # its installed unit/script content is not what this client version ships
    # (an ``enabled`` unit from an older version can be broken -- e.g. the
    # WantedBy=multi-user.target ordering cycle -- so content staleness must
    # count as drift), the desired file is missing this machine's client key,
    # or the live file has drifted from it. The heal only ever adds -- desired
    # lines from the VM and the live file are unioned, so a key another device
    # added is kept.
    state = access.read_reconciler_state()
    desired = state.desired_authorized_keys
    is_client_key_listed = desired is not None and target.client_public_key.strip() in {
        line.strip() for line in desired.splitlines()
    }
    is_installed_content_current = state.installed_content_hash == expected_reconciler_content_hash()
    if (
        not state.is_unit_enabled
        or not is_installed_content_current
        or desired is None
        or not is_client_key_listed
        or not state.is_live_matching_desired
    ):
        logger.debug("Healing adoption drift on host {} (reconciler/desired-state out of date)", target.host_id)
        live_content = access.read_vm_root_authorized_keys()
        merged_existing = (desired or "") + "\n" + (live_content or "")
        healed_desired = render_desired_authorized_keys(merged_existing, (target.client_public_key,))
        access.install_reconciler(healed_desired)

    # Both endpoints must serve exactly their user-origin pinned keys. A
    # mismatch here is somebody else's re-key: refuse (leave pins untouched)
    # rather than re-trusting material this user's devices never made.
    for kind in AdoptionEndpointKind:
        port = _endpoint_port(target, kind)
        pin = _endpoint_pin(target.known_hosts_path, target.host_id, target.address, port)
        if pin is None or pin.origin is not HostKeyOrigin.USER:
            # The marker says adopted but the pin is missing or bootstrap-origin
            # (e.g. the store was rebuilt from a rendered file): re-rotate, which
            # re-establishes a user-origin key end to end.
            logger.debug("Re-rotating {} host key for adopted host {} (no user-origin pin)", kind, target.host_id)
            rotate_endpoint_host_key(access, target, kind)
        elif not access.is_endpoint_serving_host_key(port, pin.public_key):
            raise HostKeyDriftError(
                f"adopted host {target.host_id} endpoint {target.address}:{port} ({kind}) is not serving its "
                "user-origin pinned key; refusing to re-trust it. If you rebuilt or re-keyed this host on "
                "purpose, re-adopt it (e.g. `mngr imbue_cloud hosts rotate`)."
            )
        else:
            pass


@pure
def _is_rsa_private_key(private_key_text: str) -> bool:
    """Whether a client private key is RSA, tolerating both PEM and OpenSSH containers."""
    key_bytes = private_key_text.encode("utf-8")
    for load_private_key in (serialization.load_pem_private_key, serialization.load_ssh_private_key):
        try:
            private_key = load_private_key(key_bytes, password=None)
        except (ValueError, TypeError, UnsupportedAlgorithm):
            continue
        return isinstance(private_key, rsa.RSAPrivateKey)
    return False


def ensure_client_key_current(access: SliceVmAccessInterface, target: SliceAdoptionTarget) -> None:
    """Resume an in-flight client-key rotation, and rotate a legacy RSA client key to Ed25519.

    Subsumes the retired client-side RSA -> Ed25519 migration for slices: hosts
    leased before the Ed25519 keygen switch hold RSA-4096 client keys, which
    keep working for SSH but cannot sign the owner-exec envelopes the hosted
    web chrome uses. Rotating through the reconciler desired state (unlike the
    old raw ``authorized_keys`` append, which cidata replay and the reconciler
    both revert) survives VM restarts, and the retired RSA key is de-authorized
    when done. Runs after adoption/verification so the reconciler is installed;
    the pending-state check makes a crash mid-rotation converge on the next
    full verification even though the half-swapped key already reads as
    Ed25519.
    """
    is_rotation_pending = load_pending_client_key_rotation(target.host_state_dir) is not None
    if not is_rotation_pending:
        private_key_path = target.host_state_dir / CLIENT_KEY_NAME
        public_key_path = target.host_state_dir / f"{CLIENT_KEY_NAME}.pub"
        if not private_key_path.is_file() or not public_key_path.is_file():
            return
        try:
            private_key_text = private_key_path.read_text()
        except OSError as e:
            logger.warning("Could not read the client key for host {}: {}", target.host_id, e)
            return
        if not _is_rsa_private_key(private_key_text):
            return
        logger.debug("Rotating the legacy RSA client key of host {} to Ed25519", target.host_id)
    rotate_client_key(access, target)


def _has_local_evidence_of_unfinished_key_work(target: SliceAdoptionTarget) -> bool:
    """Whether the per-host state dir says key work still needs SSH round trips.

    All three signals are pure-local file reads: an in-flight client-key
    rotation, an in-flight host-key rotation (either endpoint), or a legacy
    RSA client key awaiting the Ed25519 rotation. Each converges through one
    full verification pass, after which the evidence is gone.
    """
    if load_pending_client_key_rotation(target.host_state_dir) is not None:
        return True
    if any(load_pending_host_key_rotation(target.host_state_dir, kind) is not None for kind in AdoptionEndpointKind):
        return True
    private_key_path = target.host_state_dir / CLIENT_KEY_NAME
    try:
        private_key_text = private_key_path.read_text()
    except OSError:
        return False
    return _is_rsa_private_key(private_key_text)


def ensure_adopted(
    access: SliceVmAccessInterface,
    target: SliceAdoptionTarget,
    is_full_verification: bool,
) -> None:
    """Idempotently adopt (or re-verify) a leased slice.

    Marker absent: run full adoption. Marker present: a no-op unless
    ``is_full_verification``, and even then the SSH-visiting verification is
    durable: once a host has been fully verified at the current
    :data:`ADOPTION_SCHEMA_VERSION`, later calls are pure-local no-ops until
    the stamp is invalidated (restart/relocation --
    :func:`invalidate_adoption_verification`), the schema version bumps (a
    code migration), or local pending-rotation/RSA evidence says key work is
    unfinished (:func:`_has_local_evidence_of_unfinished_key_work`). Drift the
    stamp can no longer see is caught by the strict pinned-key SSH handshake
    (which refuses exactly like verification would) and healed by the in-VM
    reconciler at boot.
    Both the adopt and the full-verification paths finish by bringing the
    per-host client key current (see :func:`ensure_client_key_current`).
    """
    marker = load_adoption_marker(target.host_state_dir)
    if marker is None:
        _adopt(access, target)
        ensure_client_key_current(access, target)
        return
    if not is_full_verification:
        return
    if marker.verified_schema_version >= ADOPTION_SCHEMA_VERSION and not _has_local_evidence_of_unfinished_key_work(
        target
    ):
        return
    _verify_and_heal(access, target)
    ensure_client_key_current(access, target)
    _stamp_marker_verified(target.host_state_dir, marker)


def _pending_client_key_rotation_path(host_state_dir: Path) -> Path:
    return host_state_dir / _PENDING_CLIENT_KEY_ROTATION_FILENAME


def load_pending_client_key_rotation(host_state_dir: Path) -> PendingClientKeyRotation | None:
    """Read the persisted in-flight client-key rotation, or None when there is none."""
    path = _pending_client_key_rotation_path(host_state_dir)
    if not path.exists():
        return None
    try:
        return PendingClientKeyRotation.model_validate_json(path.read_text())
    except (OSError, ValueError) as e:
        logger.warning("Could not parse pending client-key rotation state {} (ignoring it): {}", path, e)
        return None


def rotate_client_key(access: SliceVmAccessInterface, target: SliceAdoptionTarget) -> str:
    """Rotate this host's per-host client key; returns the new public key.

    Ordering never strands the host: the new key is authorized on both
    endpoints and verified to authenticate before the local key files are
    swapped, and the old key is de-authorized only after the swap. A crash at
    any step leaves at least one locally-held key authorized; re-running
    converges from the persisted pending state.
    """
    host_state_dir = target.host_state_dir
    active_public_key_path = host_state_dir / f"{CLIENT_KEY_NAME}.pub"
    next_private_key_path = host_state_dir / _NEXT_CLIENT_KEY_NAME
    next_public_key_path = host_state_dir / f"{_NEXT_CLIENT_KEY_NAME}.pub"

    pending = load_pending_client_key_rotation(host_state_dir)
    if pending is None:
        save_ssh_keypair(host_state_dir, _NEXT_CLIENT_KEY_NAME)
        pending = PendingClientKeyRotation(
            old_public_key=active_public_key_path.read_text().strip(),
            new_public_key=next_public_key_path.read_text().strip(),
            started_at=datetime.now(timezone.utc),
        )
        atomic_write(_pending_client_key_rotation_path(host_state_dir), pending.model_dump_json(indent=2))

    is_already_swapped = active_public_key_path.read_text().strip() == pending.new_public_key
    if not is_already_swapped and not next_private_key_path.exists():
        # A previous run crashed between the two swap renames below: the next
        # private key is only ever consumed by the first rename, so its absence
        # (with the pending state live and the active pub still old) proves the
        # private half is already in place while the public half is not. Finish
        # the swap so the on-disk keypair is consistent again.
        if next_public_key_path.exists():
            next_public_key_path.replace(active_public_key_path)
        else:
            atomic_write(active_public_key_path, pending.new_public_key + "\n")
        is_already_swapped = True
    if not is_already_swapped:
        # Authorize the new key on both endpoints (desired-state file for the
        # VM via the reconciler; container file directly).
        state = access.read_reconciler_state()
        desired = state.desired_authorized_keys
        if desired is None:
            raise AdoptionError(
                f"host {target.host_id} has no desired-state authorized_keys on its VM; adopt it before "
                "rotating its client key"
            )
        access.install_reconciler(render_desired_authorized_keys(desired, (pending.new_public_key,)))
        access.append_container_authorized_key(pending.new_public_key)

        # Prove the new key opens both doors before retiring the old one.
        if not access.can_authenticate(target.vm_port, next_private_key_path):
            raise AdoptionError(
                f"rotated client key was authorized but does not authenticate on the VM endpoint of "
                f"{target.host_id}; the previous key is untouched"
            )
        if not access.can_authenticate(target.container_port, next_private_key_path):
            raise AdoptionError(
                f"rotated client key was authorized but does not authenticate on the container endpoint of "
                f"{target.host_id}; the previous key is untouched"
            )

        # Swap the local files: from here on this machine opens the host with
        # the new key.
        next_private_key_path.replace(host_state_dir / CLIENT_KEY_NAME)
        next_public_key_path.replace(active_public_key_path)

    # De-authorize the retired key everywhere, then clear the pending state.
    state_after_swap = access.read_reconciler_state()
    desired_after_swap = state_after_swap.desired_authorized_keys or ""
    access.install_reconciler(remove_key_from_desired_authorized_keys(desired_after_swap, pending.old_public_key))
    access.remove_container_authorized_key(pending.old_public_key)
    _pending_client_key_rotation_path(host_state_dir).unlink(missing_ok=True)
    logger.info("Rotated the client key for host {}", target.host_id)
    return pending.new_public_key


class ParamikoSliceVmAccess(SliceVmAccessInterface):
    """Real slice access: every operation runs over the VM-root sshd via paramiko, strictly host-key checked."""

    host_id: HostId = Field(frozen=True, description="The leased host's mngr host id")
    address: str = Field(frozen=True, description="The slice's box address")
    vm_port: int = Field(frozen=True, description="Box port forwarded to the VM-root sshd")
    ssh_user: str = Field(frozen=True, default="root", description="User on the VM-root sshd")
    private_key_path: Path = Field(frozen=True, description="Per-host client private key that opens the VM")
    known_hosts_path: Path = Field(frozen=True, description="Per-host known_hosts file (store-rendered)")

    def _connect(self, port: int, private_key_path: Path) -> paramiko.SSHClient:
        client = paramiko.SSHClient()
        try:
            client.load_host_keys(str(self.known_hosts_path))
        except OSError as e:
            raise AdoptionError(f"failed to load known_hosts {self.known_hosts_path}: {e}") from e
        client.set_missing_host_key_policy(paramiko.RejectPolicy())
        try:
            client.connect(
                hostname=self.address,
                port=port,
                username=self.ssh_user,
                key_filename=str(private_key_path),
                allow_agent=False,
                look_for_keys=False,
                timeout=_SSH_CONNECT_TIMEOUT_SECONDS,
            )
        except (paramiko.SSHException, OSError) as e:
            client.close()
            raise AdoptionError(f"SSH connect to {self.address}:{port} failed: {e}") from e
        # Keepalives so a silently dead path surfaces as a transport error
        # instead of leaving a blocked read waiting forever (see
        # SSH_KEEPALIVE_INTERVAL_SECONDS in imbue.mngr.hosts.outer_host).
        transport = client.get_transport()
        if transport is not None:
            transport.set_keepalive(SSH_KEEPALIVE_INTERVAL_SECONDS)
        return client

    def _run(self, command: str, timeout_seconds: float) -> CommandResult:
        client = self._connect(self.vm_port, self.private_key_path)
        try:
            try:
                _stdin, stdout, stderr = client.exec_command(command, timeout=timeout_seconds)
                # Drain the streams before asking for the exit status: the
                # reads honor the channel timeout and EOF at command exit,
                # while recv_exit_status alone blocks with no timeout (and
                # waiting for exit before reading can deadlock on the channel
                # window for chatty commands).
                stdout_text = stdout.read().decode()
                stderr_text = stderr.read().decode()
                exit_status = stdout.channel.recv_exit_status()
            except (paramiko.SSHException, OSError) as e:
                raise AdoptionError(f"SSH command on {self.address}:{self.vm_port} failed: {e}") from e
        finally:
            client.close()
        return CommandResult(stdout=stdout_text, stderr=stderr_text, success=exit_status == 0)

    def _run_checked(self, command: str, timeout_seconds: float, label: str) -> CommandResult:
        result = self._run(command, timeout_seconds)
        if not result.success:
            raise AdoptionError(
                f"{label} failed on host {self.host_id} ({self.address}:{self.vm_port}): "
                f"stderr={result.stderr.strip()!r}"
            )
        return result

    def read_vm_root_authorized_keys(self) -> str | None:
        result = self._run(
            "if [ -f /root/.ssh/authorized_keys ]; then cat /root/.ssh/authorized_keys; else echo MNGR_AK_ABSENT; fi",
            _VM_COMMAND_TIMEOUT_SECONDS,
        )
        if not result.success:
            raise AdoptionError(
                f"could not read the VM root authorized_keys on {self.host_id}: {result.stderr.strip()!r}"
            )
        if result.stdout.strip() == "MNGR_AK_ABSENT":
            return None
        return result.stdout

    def install_reconciler(self, desired_authorized_keys: str) -> None:
        self._run_checked(
            build_reconciler_install_command(desired_authorized_keys),
            _RECONCILER_INSTALL_TIMEOUT_SECONDS,
            "reconciler install",
        )

    def read_reconciler_state(self) -> SliceReconcilerState:
        result = self._run_checked(
            build_read_reconciler_state_command(), _VM_COMMAND_TIMEOUT_SECONDS, "reconciler state read"
        )
        return parse_reconciler_state_output(result.stdout)

    def install_vm_host_key(self, private_key_pem: str, public_key: str) -> None:
        self._run_checked(
            build_vm_host_key_install_command(private_key_pem, public_key),
            _VM_COMMAND_TIMEOUT_SECONDS,
            "VM host-key install",
        )

    def install_container_host_key(self, private_key_pem: str, public_key: str) -> None:
        self._run_checked(
            build_container_host_key_install_command(self.host_id, private_key_pem, public_key),
            _VM_COMMAND_TIMEOUT_SECONDS,
            "container host-key install",
        )

    def append_container_authorized_key(self, public_key: str) -> None:
        self._run_checked(
            build_container_authorized_key_append_command(self.host_id, public_key),
            _VM_COMMAND_TIMEOUT_SECONDS,
            "container authorized_keys append",
        )

    def remove_container_authorized_key(self, public_key: str) -> None:
        self._run_checked(
            build_container_authorized_key_remove_command(self.host_id, public_key),
            _VM_COMMAND_TIMEOUT_SECONDS,
            "container authorized_keys removal",
        )

    def is_endpoint_serving_host_key(self, port: int, public_key: str) -> bool:
        try:
            return is_server_presenting_host_key(self.address, port, public_key)
        except MngrError as e:
            logger.warning("Malformed public key while probing {}:{}: {}", self.address, port, e)
            return False

    def can_authenticate(self, port: int, private_key_path: Path) -> bool:
        try:
            client = self._connect(port, private_key_path)
        except AdoptionError:
            return False
        client.close()
        return True
