"""Adoption of leased imbue_cloud slices: the user's devices take ownership of the host's SSH material.

A freshly-leased slice's trust material is all bake-time: both sshd host keys
were generated by the operator tooling and recorded in the pool DB, and the VM
root's ``authorized_keys`` is owned by the carve's cloud-init scripts (which
replay on every VM start). Adoption flips ownership to the user, exactly once
per host, from the user's own machine:

- an in-VM systemd **reconciler** unit re-asserts a root-owned desired-state
  ``authorized_keys`` (and the rotated sshd host key) on every boot, *after*
  cloud-init's replay -- so a restart can never again strand the owner;
- both endpoints' sshd host keys are **rotated** to fresh user-generated keys
  and pinned user-origin in the host-key store, so the connector's bake-time
  keys stop mattering (the store's precedence rules keep bootstrap pins from
  ever displacing these);
- a client-side **marker** in the per-host state dir records the adoption AND
  the schema version it was last fully verified at, so later connects are a
  pure-local no-op. A full SSH-visiting re-verification runs again only when
  the stamp is invalidated (restart/relocation, explicit ``hosts rotate``),
  the code's ADOPTION_SCHEMA_VERSION moves past the stamp (a migration), or
  local pending-rotation/RSA evidence shows unfinished key work. Drift the
  stamp cannot see is refused by the strict pinned-key SSH handshake (the
  same refusal verification gives) and healed by the in-VM reconciler at
  boot.

Rotation is a small persisted state machine: the fresh keypair is written to
the client's per-host state dir *before* the host is touched, so a crash at any
step leaves a host that the next run can converge on -- the unauthenticated
served-key probe decides whether the endpoint still serves the old key (redo
the install) or already serves the new one (finish by pinning it).
"""

